// Build an exact Blogger→new redirect map from imported articles.
// Reads each article's bloggerOriginalUrl and maps its path → /<new-slug>.
// Output: src/lib/blogger-redirects.ts (imported by the proxy/middleware).
// Run: node --env-file=.env.local scripts/build-blogger-redirects.mjs
import { initializeApp, cert, getApps } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
import { writeFileSync } from "fs";

const app = getApps()[0] || initializeApp({
  credential: cert({
    projectId: process.env.FIREBASE_PROJECT_ID,
    clientEmail: process.env.FIREBASE_CLIENT_EMAIL,
    privateKey: process.env.FIREBASE_PRIVATE_KEY?.replace(/\\n/g, "\n"),
  }),
});
const db = getFirestore(app);

const snap = await db.collection("articles").where("status", "==", "published").get();
const map = {};
let withBlogger = 0;
for (const d of snap.docs) {
  const a = d.data();
  if (!a.bloggerOriginalUrl || !a.slug) continue;
  try {
    const path = new URL(a.bloggerOriginalUrl).pathname; // /YYYY/MM/slug.html
    map[path] = `/${a.slug}`;
    // Also map the trailing-slash and ?m=1 mobile variants are handled in proxy.
    withBlogger++;
  } catch {
    /* skip bad url */
  }
}

const sorted = Object.fromEntries(Object.entries(map).sort());
const ts = `// AUTO-GENERATED by scripts/build-blogger-redirects.mjs — do not edit by hand.
// Exact Blogger post path -> new article path (301).
export const bloggerRedirects: Record<string, string> = ${JSON.stringify(sorted, null, 2)};
`;
writeFileSync("src/lib/blogger-redirects.ts", ts);
console.log(`Wrote src/lib/blogger-redirects.ts with ${withBlogger} exact redirects.`);
